from typing import TypeVar

# **Описание**: Создайте функцию swap_values, которая принимает два значения одного типа и возвращает кортеж с этими значениями в обратном порядке.
#
# **Входные данные**: Встроенные данные в коде (без внешнего ввода)
#
# **Выходные данные**: Функция swap_values с корректными аннотациями типов, возвращающая tuple[T, T]
#
# **Ограничения**:
# - Используйте TypeVar для обобщения типа значений
# - Функция должна принимать два параметра одного типа T
# - Возвращаемый тип должен быть tuple[T, T]
# - Функция должна возвращать кортеж с переставленными местами значениями
#
# **Примеры**:
# Input: swap_values(10, 20)
# Output: (20, 10)
#
# Входные данные: swap_values('first', 'second')
# Output: ('second', 'first')

# Ваш код здесь

T = TypeVar("T")


def swap_values(n1: T, n2: T) -> tuple[T, T]:
    return n2, n1


print(swap_values(10, 20))
print(swap_values('first', 'second'))
